export type PassengerCategory = "adult" | "child" | "infant" | "unknown"

export type PassengerContactType = "email" | "phone"

export interface PassengerIdentity {
	givenName?: string
	middleName?: string
	familyName?: string
	title?: string
	gender?: string
	dateOfBirth?: string
	nationality?: string
}

export interface PassengerContact {
	id: string
	type: PassengerContactType
	value: string
	belongsTo: "passenger" | "other"
	relatedPersonPassengerId?: string
}

export interface TravelDocument {
	id: string
	type: string
	documentNumber?: string
	issuingCountry?: string
	expirationDate?: string
}

export interface ProviderPassengerReference {
	provider: string
	offerId: string
	providerPassengerId: string
	providerPassengerType: string | null
	age: number | null
}

export interface Passenger {
	id: string
	category: PassengerCategory
	identity: PassengerIdentity
	contacts: PassengerContact[]
	travelDocuments: TravelDocument[]
	providerReferences: ProviderPassengerReference[]
}

export interface PassengerRelationship {
	passengerId: string
	relatedPassengerId: string
	type: "responsible_adult"
}

export interface OfferPassengerSource {
	id: string
	type: string | null
	age: number | null
}

export interface OfferPassengerCollectionSource {
	id: string
	passengers?: readonly OfferPassengerSource[]
}

export interface PassengerCollection {
	passengers: Passenger[]
	relationships: PassengerRelationship[]
}

export interface CreatePassengerCollectionOptions {
	provider: string
	createInternalId: () => string
	getCategory?: (passenger: OfferPassengerSource) => PassengerCategory
}

export type PassengerDomainErrorCode =
	| "INVALID_PROVIDER"
	| "INVALID_OFFER_ID"
	| "MISSING_OFFER_PASSENGERS"
	| "INVALID_PROVIDER_PASSENGER_ID"
	| "DUPLICATE_PROVIDER_PASSENGER_ID"
	| "INVALID_INTERNAL_PASSENGER_ID"
	| "DUPLICATE_INTERNAL_PASSENGER_ID"

export class PassengerDomainError extends Error {
	readonly code: PassengerDomainErrorCode
	constructor(message: string, code: PassengerDomainErrorCode) {
		super(message)
		this.name = "PassengerDomainError"
		this.code = code
	}
}

/**
 * Creates an in-memory passenger draft for every passenger on an offer.
 *
 * Internal IDs are generated by the caller so the app can use its chosen
 * ID-generation strategy without coupling this domain module to a platform API.
 * Provider IDs are copied exactly and are never inferred from array positions.
 */
export function createPassengerCollectionFromOffer(
	offer: OfferPassengerCollectionSource,
	options: CreatePassengerCollectionOptions,
): PassengerCollection {
	const provider = options.provider.trim()
	if (!provider) {
		throw new PassengerDomainError("A provider identifier is required.", "INVALID_PROVIDER")
	}

	if (typeof offer.id !== "string" || !offer.id.trim()) {
		throw new PassengerDomainError("A valid offer ID is required.", "INVALID_OFFER_ID")
	}

	if (!Array.isArray(offer.passengers) || offer.passengers.length === 0) {
		throw new PassengerDomainError(
			"The selected offer does not contain passenger identities.",
			"MISSING_OFFER_PASSENGERS",
		)
	}

	const providerPassengerIds = new Set<string>()
	const internalPassengerIds = new Set<string>()

	const passengers = offer.passengers.map((offerPassenger) => {
		if (typeof offerPassenger.id !== "string" || !offerPassenger.id.trim()) {
			throw new PassengerDomainError(
				"An offer passenger is missing a valid provider passenger ID.",
				"INVALID_PROVIDER_PASSENGER_ID",
			)
		}

		if (providerPassengerIds.has(offerPassenger.id)) {
			throw new PassengerDomainError(
				"The offer contains duplicate provider passenger IDs.",
				"DUPLICATE_PROVIDER_PASSENGER_ID",
			)
		}
		providerPassengerIds.add(offerPassenger.id)

		const internalId = options.createInternalId()
		if (typeof internalId !== "string" || !internalId.trim()) {
			throw new PassengerDomainError(
				"Internal passenger ID generation returned an invalid ID.",
				"INVALID_INTERNAL_PASSENGER_ID",
			)
		}
		if (internalPassengerIds.has(internalId)) {
			throw new PassengerDomainError(
				"Internal passenger ID generation returned a duplicate ID.",
				"DUPLICATE_INTERNAL_PASSENGER_ID",
			)
		}
		internalPassengerIds.add(internalId)

		return {
			id: internalId,
			category: options.getCategory?.(offerPassenger) ?? "unknown",
			identity: {},
			contacts: [],
			travelDocuments: [],
			providerReferences: [
				{
					provider,
					offerId: offer.id,
					providerPassengerId: offerPassenger.id,
					providerPassengerType: offerPassenger.type,
					age: offerPassenger.age,
				},
			],
		}
	})

	return { passengers, relationships: [] }
}

export type PassengerRelationshipIssueCode =
	| "DUPLICATE_INTERNAL_PASSENGER_ID"
	| "UNKNOWN_PASSENGER"
	| "SELF_RELATIONSHIP"
	| "DUPLICATE_RELATIONSHIP"
	| "MULTIPLE_RESPONSIBLE_ADULTS"

export interface PassengerRelationshipIssue {
	code: PassengerRelationshipIssueCode
	passengerId: string
	relatedPassengerId?: string
}

/**
 * Validates relationship structure only. Passenger-category eligibility and
 * provider-specific limits belong to the selected provider's requirements layer.
 */
export function validatePassengerRelationships(
	passengers: readonly Passenger[],
	relationships: readonly PassengerRelationship[],
): PassengerRelationshipIssue[] {
	const issues: PassengerRelationshipIssue[] = []
	const passengerIds = new Set<string>()

	for (const passenger of passengers) {
		if (passengerIds.has(passenger.id)) {
			issues.push({
				code: "DUPLICATE_INTERNAL_PASSENGER_ID",
				passengerId: passenger.id,
			})
		}
		passengerIds.add(passenger.id)
	}

	const relationshipKeys = new Set<string>()
	const responsibleAdultsByPassenger = new Set<string>()

	for (const relationship of relationships) {
		const { passengerId, relatedPassengerId, type } = relationship

		if (!passengerIds.has(passengerId) || !passengerIds.has(relatedPassengerId)) {
			issues.push({
				code: "UNKNOWN_PASSENGER",
				passengerId,
				relatedPassengerId,
			})
			continue
		}

		if (passengerId === relatedPassengerId) {
			issues.push({
				code: "SELF_RELATIONSHIP",
				passengerId,
				relatedPassengerId,
			})
			continue
		}

		const relationshipKey = `${type}:${passengerId}:${relatedPassengerId}`
		if (relationshipKeys.has(relationshipKey)) {
			issues.push({
				code: "DUPLICATE_RELATIONSHIP",
				passengerId,
				relatedPassengerId,
			})
			continue
		}
		relationshipKeys.add(relationshipKey)

		if (type === "responsible_adult") {
			if (responsibleAdultsByPassenger.has(passengerId)) {
				issues.push({
					code: "MULTIPLE_RESPONSIBLE_ADULTS",
					passengerId,
					relatedPassengerId,
				})
				continue
			}
			responsibleAdultsByPassenger.add(passengerId)
		}
	}

	return issues
}
